func makeRepo(t *testing.T, withModule bool) string {
	t.Helper()
	dir := t.TempDir()
	if withModule {
		writeFixture(t, dir, "go.mod", "module example.com/project\n\ngo 1.22\n")
	}
	return dir
}

func writeFixture(t testing.TB, root, name, content string) {
	t.Helper()
	p := filepath.Join(root, name)
	if err := os.MkdirAll(filepath.Dir(p), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), 0644); err != nil {
		t.Fatal(err)
	}
}

func TestSimpleHealthyProject(t *testing.T) {
	root := makeRepo(t, true)
	writeFixture(t, root, "math/sum.go", "package math\nfunc Sum(a,b int) int { return a+b }\n")
	report, err := analyze(root, false)
	if err != nil {
		t.Fatal(err)
	}
	if report.AnalysisStatus != "complete" || report.CodeHealthScore == nil {
		t.Fatalf("unexpected status: %+v", report)
	}
	if *report.CodeHealthScore != 10 {
		t.Errorf("simple project should have 10, got %.1f", *report.CodeHealthScore)
	}
	if len(report.Packages) != 1 || report.Files[0].Path != "math/sum.go" {
		t.Errorf("unexpected file hierarchy: %+v", report)
	}
}

