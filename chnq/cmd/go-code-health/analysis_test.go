func TestComplexCodeScoresLower(t *testing.T) {
	root := makeRepo(t, true)
	healthy := "package p\nfunc Easy(n int) int { return n+1 }\n"
	writeFixture(t, root, "simple.go", healthy)
	baseline, err := analyze(root, false)
	if err != nil {
		t.Fatal(err)
	}
	var body strings.Builder
	body.WriteString("package p\nfunc Hard(x int) int {\n")
	for i := 0; i < 10; i++ {
		_, _ = fmt.Fprintf(&body, "if x > %d { x++ }\n", i)
	}
	body.WriteString("return x\n}\n")
	writeFixture(t, root, "hard.go", body.String())
	report, err := analyze(root, false)
	if err != nil {
		t.Fatal(err)
	}
	if *report.CodeHealthScore >= *baseline.CodeHealthScore {
		t.Errorf("adding harder code should lower score: baseline %.1f new %.1f", *baseline.CodeHealthScore, *report.CodeHealthScore)
	}
	if report.Files[0].Score >= report.Files[1].Score {
		t.Errorf("hard.go should be lower: %+v", report.Files)
	}
}

