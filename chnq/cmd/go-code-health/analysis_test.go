		"func B(x int) int {\n" + strings.Repeat("x = x * 2; x = x / 3; x = x + 4\n", 4) + "return x\n}\n"
	writeFixture(t, root, "dup.go", content)
	report, err := analyze(root, false)
	if err != nil {
		t.Fatal(err)
	}
